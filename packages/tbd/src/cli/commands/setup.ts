/** Inspect the tbd-owned part of Codex hooks while preserving unrelated hooks. */
export async function inspectCodexHooksSurface(cwd: string): Promise<ManagedArtifactInspection> {
  const codexPaths = getCodexPaths(cwd);
  let parsed: { hooks?: Record<string, unknown[]> };
  try {
    parsed = JSON.parse(await readFile(codexPaths.hooks, 'utf-8')) as {
      hooks?: Record<string, unknown[]>;
    };
  } catch (error) {
    if (
      error instanceof Error &&
      'code' in error &&
      typeof error.code === 'string' &&
      error.code === 'ENOENT'
    ) {
      return { state: 'missing' };
    }
    return { state: 'user-owned' };
  }

  const isTbdOwned = (entry: unknown): boolean => {
    const hooks = (entry as { hooks?: { command?: string }[] }).hooks ?? [];
    return hooks.some((hook) => hook.command?.includes('.codex/'));
  };
  const actualOwned: Record<string, unknown[]> = {};
  for (const [event, entries] of Object.entries(parsed.hooks ?? {})) {
    const owned = entries.filter(isTbdOwned);
    if (owned.length > 0) {
      actualOwned[event] = owned;
    }
  }
  if (Object.keys(actualOwned).length === 0) {
    return { state: 'user-owned' };
  }

  const useGhCli = await useGhCliForProject(cwd);
  if (!isDeepStrictEqual(actualOwned, getCodexHooksConfig(useGhCli).hooks)) {
    return { state: 'stale' };
  }

  const expectedScripts = new Map<string, string>([
    [join(cwd, CODEX_SESSION_SCRIPT_REL), TBD_SESSION_SCRIPT],
    [join(cwd, CODEX_CLOSING_REMINDER_REL), TBD_CLOSE_PROTOCOL_SCRIPT],
  ]);
  if (useGhCli) {
    expectedScripts.set(join(cwd, CODEX_GH_CLI_SCRIPT_REL), await loadGhCliScript('codex'));
  }
  for (const [path, expected] of expectedScripts) {
    try {
      if ((await readFile(path, 'utf-8')) !== expected) {
        return { state: 'stale' };
      }
    } catch {
      return { state: 'missing' };
    }
  }
  if (!useGhCli && (await pathExists(join(cwd, CODEX_GH_CLI_SCRIPT_REL)))) {
    return { state: 'stale' };
  }
  return { state: 'current' };
}

